def stdlib_extension_modules() -> set[str]:
    """Names of the build interpreter's own (CPython stdlib) extension modules, e.g. {"_ctypes", "select"}."""
    dirs = [Path(sysconfig.get_paths()["platstdlib"]) / "lib-dynload", Path(sys.base_prefix) / "DLLs",
            Path(sysconfig.get_config_var("DESTSHARED") or "/nonexistent")]
    out = set()
    for d in dirs:
        if d.is_dir():
            out |= {f.name.split(".")[0] for f in d.iterdir() if f.suffix.lower() in (".so", ".pyd")}
    return out


def classify(dist: Path) -> tuple[dict[str, list[str]], list[str]]:
    """Map every native file in the folder to a component; return (component → files, problems)."""
    found: dict[str, list[str]] = {}
    problems: list[str] = []
    exe = "pdfcore.exe" if sys.platform == "win32" else "pdfcore"
    stdlib_ext = stdlib_extension_modules()
    for f in sorted(dist.rglob("*")):
        if not f.is_file():
            continue
        rel = f.relative_to(dist).as_posix()
        name = f.name
        if name == exe:
            found.setdefault("pdfcore", []).append(rel)
            continue
        is_native = bool(re.search(r"\.(so|pyd|dylib|dll)$", name, re.I)) or name == "Python"
        if not is_native:
            continue
        if any(re.search(rx, name, re.I) for rx in FORBIDDEN_NATIVE):
            problems.append(f"{rel}: not allowed in the sidecar (copyleft, or OpenSSL/readline the text path never needs)")
            continue
        for rx, comp in NATIVE_RULES:
            if re.search(rx, name, re.I):
                found.setdefault(comp, []).append(rel)
                break
        else:
            if re.search(r"\.(so|pyd)$", name, re.I) and name.split(".")[0] in stdlib_ext:
                found.setdefault("cpython", []).append(rel)
                continue
            problems.append(f"{rel}: unknown native file — identify its licence and add it to NATIVE_RULES")
    return found, problems


def is_pbs_python() -> bool:
    """python-build-standalone (uv's interpreters) links CPython's optional C libraries into libpython."""
    try:
        from nuitka.PythonFlavors import isPythonBuildStandalonePython

        return bool(isPythonBuildStandalonePython())
    except Exception:
        return "/uv/python/" in sys.base_prefix.replace("\\", "/")


def write_licenses(dist: Path, found: dict[str, list[str]], nuitka_lic: Path, meta: dict) -> None:
    import pypdfium2

    meta = dict(meta)
    meta.setdefault("pdfium_py", pypdfium2.version.PYPDFIUM_INFO)
    meta.setdefault("pdfium_ver", pypdfium2.version.PDFIUM_INFO)
    comps = ["pdfcore", "nuitka", "cpython", "pypdfium2", "pdfium"] + sorted(set(found) - {"pdfcore", "cpython", "pdfium"})
    lines = [
        "# Third-party licenses — pdfcore sidecar",
        "",
        f"`pdfcore {meta['version']}` for `{meta['target']}`, built {meta['built']} with Nuitka {meta['nuitka']} "
        f"(Apache-2.0) and CPython {meta['pyver']}. Generated by `tools/build_sidecar.py` from the files actually in "
        "this folder; every bundled package and native library is listed with its full license text below.",
        "",
        "No GPL, AGPL or LGPL code is included. NumPy, Pillow and the rest of PDF Studio's dependencies are **not** "
        "bundled (the sidecar only extracts text), so numpy's LICENSE.txt does not apply to this artifact.",
        "",
        "| Component | License | Used for | Files |",
        "|---|---|---|---|",
    ]
    for c in comps:
        title, lic, use = COMPONENTS[c]
        files = found.get(c, [])
        if c == "nuitka":
            files = ["(compiled into the executable)"]
        if c == "pypdfium2":
            files = ["(compiled into the executable)"]
        shown = ", ".join(f"`{f}`" for f in files[:4]) + (f" +{len(files) - 4} more" if len(files) > 4 else "")
        lines.append(f"| {title.format(**meta)} | {lic} | {use} | {shown} |")
    if meta.get("static_python"):
        from sidecar_license_texts import PBS_STATIC

        names = ", ".join(f"{c} ({l})" for c, l, _ in PBS_STATIC)
        lines.append(f"| C libraries inside libpython (python-build-standalone build) | permissive: {names} | "
                     "parts of the CPython runtime; only what the sidecar imports is executed | `libpython` |")
    lines += ["", "Python packages compiled into the executable: `pdfcore` (words, sidecar), `pypdfium2`, "
              "`pypdfium2_raw`, `pypdfium2_cfg`, and the CPython standard-library modules they import.", ""]
    texts: list[tuple[str, str]] = [("pdfcore / PDF Studio — MIT", _read(ROOT / "LICENSE"))]
    texts.append((f"Nuitka {meta['nuitka']} runtime — Apache-2.0", _read(nuitka_lic)))
    texts.append((f"CPython {meta['pyver']} — PSF License (with the licenses of code it incorporates)",
                  _read(python_license_file())))
    for p in pypdfium2_license_files():
        sub = p.as_posix().split("/licenses/", 1)[1]
        texts.append((f"pypdfium2 / PDFium — {sub}", _read(p)))
    if "libffi" in found:
        texts.append(("libffi — MIT", LIBFFI_TEXT))
    if "zlib" in found:
        texts.append(("zlib — Zlib", ZLIB_TEXT))
    if "msvc" in found:
        texts.append(("Microsoft Visual C++ runtime", MSVC_TEXT))
    if meta.get("static_python"):
        from sidecar_license_texts import PBS_STATIC

        apache = _read(nuitka_lic)
        for comp, spdx, body in PBS_STATIC:
            texts.append((f"{comp} — {spdx} (statically linked into libpython by python-build-standalone)",
                          apache if body == "apache" else body))
    lines += ["# License texts", ""]
    for title, body in texts:
        lines += [f"## {title}", "", "```text", body.rstrip("\n").replace("```", "'''"), "```", ""]
    (dist / "THIRD_PARTY_LICENSES.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")


