#!/usr/bin/env python3
"""Build the standalone ``pdfcore`` sidecar (BAR Estimating integration contract §2, §3, §6).

    python tools/build_sidecar.py [--out dist] [--jobs N] [--skip-compile]

Produces, for the host platform (``darwin-arm64`` or ``win32-x64``):

    dist/pdfcore-<ver>-<target>/          self-contained --onedir folder
        pdfcore[.exe]                     the program (console subsystem on Windows — see below)
        schemas/pdfcore-words-1.schema.json
        THIRD_PARTY_LICENSES.md           every bundled component + full license texts
        LICENSE                           PDF Studio (MIT)
    dist/pdfcore-<ver>-<target>.zip
    dist/pdfcore-<ver>-<target>.json      build report (size, file list, licences, checks)

Bundler: **Nuitka 2.8.x (Apache-2.0)** in ``--standalone`` (onedir) mode. Nuitka ≥ 4.0 is AGPL-3.0 with a
runtime-library exception, PyInstaller is GPL-2.0 with a bootloader exception; this script refuses any
Nuitka whose metadata is not Apache-2.0.

Windows console: the exe is a console-subsystem program so stdout/stderr reach the parent process through
pipes. BAR spawns it with ``windowsHide: true`` (Node ``child_process``), so no console window flashes.

macOS: every Mach-O in the folder is test-signed ad hoc (``codesign --force --sign -``) on a *copy*, and
quarantine/extended attributes are stripped from the artifact (``xattr -cr``).

Licensing: every file in the output folder is classified. A native library or extension module this
script cannot attribute to a known, permissively licensed component fails the build.
"""

