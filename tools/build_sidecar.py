# ----------------------------------------------------------------------------- checks
def macho_files(dist: Path) -> list[Path]:
    out = []
    for f in dist.rglob("*"):
        if f.is_file() and not f.is_symlink():
            with f.open("rb") as fh:
                magic = fh.read(4)
            if magic in (b"\xcf\xfa\xed\xfe", b"\xce\xfa\xed\xfe", b"\xca\xfe\xba\xbe", b"\xfe\xed\xfa\xcf"):
                out.append(f)
    return sorted(out)


def check_codesign(dist: Path) -> dict:
    """Ad-hoc sign a copy of every Mach-O (what BAR's build does) and run the signed copy."""
    with tempfile.TemporaryDirectory(prefix="pdfcore-codesign-") as td:
        cp = Path(td) / dist.name
        shutil.copytree(dist, cp, symlinks=True)
        files = macho_files(cp)
        bad = []
        for f in files:
            r = subprocess.run(["codesign", "--force", "--sign", "-", str(f)], capture_output=True, text=True)
            if r.returncode:
                bad.append(f"{f.relative_to(cp)}: {r.stderr.strip()}")
                continue
            v = subprocess.run(["codesign", "--verify", "--strict", str(f)], capture_output=True, text=True)
            if v.returncode:
                bad.append(f"{f.relative_to(cp)}: verify: {v.stderr.strip()}")
        run = subprocess.run([str(cp / "pdfcore"), "--version"], capture_output=True, text=True)
        return {"machO": len(files), "failed": bad, "signedCopyRuns": run.returncode == 0,
                "files": [f.relative_to(cp).as_posix() for f in files]}


def startup_times(exe: Path, runs: int = 3) -> list[float]:
    out = []
    for _ in range(runs):
        t0 = time.perf_counter()
        r = subprocess.run([str(exe), "--version"], capture_output=True)
        out.append(round(time.perf_counter() - t0, 3))
        if r.returncode:
            fail(f"{exe.name} --version failed: {r.stderr.decode(errors='replace')}")
    return out


def make_zip(folder: Path, zpath: Path) -> None:
    """Deterministic zip: sorted entries, fixed timestamps, unix permissions kept (exec bits for macOS)."""
    if zpath.exists():
        zpath.unlink()
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for f in sorted(folder.rglob("*")):
            arc = f"{folder.name}/{f.relative_to(folder).as_posix()}"
            if f.is_symlink():
                zi = zipfile.ZipInfo(arc, date_time=(2020, 1, 1, 0, 0, 0))
                zi.create_system = 3
                zi.external_attr = (0o120777 << 16)
                zf.writestr(zi, os.readlink(f))
            elif f.is_dir():
                continue
            else:
                zi = zipfile.ZipInfo(arc, date_time=(2020, 1, 1, 0, 0, 0))
                zi.create_system = 3
                mode = 0o755 if (os.access(f, os.X_OK) or f.suffix.lower() in (".exe", ".dll", ".pyd")) else 0o644
                zi.external_attr = ((0o100000 | mode) << 16)
                zi.compress_type = zipfile.ZIP_DEFLATED
                zf.writestr(zi, f.read_bytes(), compresslevel=9)


