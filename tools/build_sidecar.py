def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default=str(ROOT / "dist"), help="output folder (default: dist/)")
    ap.add_argument("--work", default=str(ROOT / "build" / "sidecar"), help="Nuitka work folder")
    ap.add_argument("--jobs", type=int, help="parallel C compile jobs")
    ap.add_argument("--skip-compile", action="store_true", help="reuse the last Nuitka output in --work")
    a = ap.parse_args()

    from pdfcore import __version__ as version

    target = target_name()
    if not SCHEMA_SRC.exists():
        fail(f"schema file missing: {SCHEMA_SRC.relative_to(ROOT)} (it ships inside the artifact)")
    json.loads(SCHEMA_SRC.read_text(encoding="utf-8"))  # must be valid JSON
    nver, nlic = nuitka_info()
    log(f"pdfcore {version} → {target}; Nuitka {nver} (Apache-2.0); Python {platform.python_version()}")

    work = Path(a.work)
    work.mkdir(parents=True, exist_ok=True)
    if not a.skip_compile:
        ensure_macos_sdk()
    built = work / "pdfcore_sidecar.dist"
    if not a.skip_compile:
        if built.exists():
            shutil.rmtree(built)
        built = compile_nuitka(work, version, a.jobs)
    elif not built.is_dir():
        fail(f"--skip-compile: nothing at {built}")

    out_dir = Path(a.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    name = f"pdfcore-{version}-{target}"
    dest = out_dir / name
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(built, dest, symlinks=True)
    (dest / "schemas").mkdir(exist_ok=True)
    shutil.copy2(SCHEMA_SRC, dest / "schemas" / SCHEMA_SRC.name)
    shutil.copy2(ROOT / "LICENSE", dest / "LICENSE")

    found, problems = classify(dest)
    if problems:
        fail("licence check of the bundle failed:\n  " + "\n  ".join(problems))
    meta = {"version": version, "target": target, "nuitka": nver, "pyver": platform.python_version(),
            "built": time.strftime("%Y-%m-%d"), "static_python": is_pbs_python()}
    write_licenses(dest, found, nlic, meta)

    exe = dest / ("pdfcore.exe" if sys.platform == "win32" else "pdfcore")
    report: dict = {"name": name, "version": version, "target": target, "nuitka": nver,
                    "python": platform.python_version(), "components": {k: sorted(v) for k, v in found.items()}}
    if sys.platform == "darwin":
        subprocess.run(["xattr", "-cr", str(dest)], check=True)
        cs = check_codesign(dest)
        report["codesign"] = cs
        if cs["failed"] or not cs["signedCopyRuns"]:
            fail("ad-hoc codesign check failed: " + "; ".join(cs["failed"] or ["signed copy did not run"]))
        log(f"codesign --force --sign - : {cs['machO']} Mach-O files OK, signed copy runs")
    v = subprocess.run([str(exe), "--version"], capture_output=True, text=True)
    first = v.stdout.splitlines()[:1]
    if v.returncode or first != [f"pdfcore {version}"] or "pdfcore-words/1" not in v.stdout:
        fail(f"--version check failed: rc={v.returncode} out={v.stdout!r} err={v.stderr!r}")
    report["startup_s"] = startup_times(exe)
    size = dir_size(dest)
    report["size_bytes"] = size
    report["size_mb"] = round(size / 1e6, 1)
    if size / 1e6 > SIZE_BUDGET_MB:
        fail(f"{name} is {size / 1e6:.1f} MB, over the {SIZE_BUDGET_MB:g} MB budget")
    zpath = out_dir / f"{name}.zip"
    make_zip(dest, zpath)
    report["zip"] = {"file": zpath.name, "bytes": zpath.stat().st_size, "sha256": sha256(zpath)}
    report["files"] = sorted(f.relative_to(dest).as_posix() for f in dest.rglob("*") if f.is_file())
    (out_dir / f"{name}.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    log(f"{dest}  {report['size_mb']} MB on disk, zip {zpath.stat().st_size / 1e6:.1f} MB, "
        f"--version {report['startup_s']} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
