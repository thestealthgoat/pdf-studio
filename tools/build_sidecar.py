# ----------------------------------------------------------------------------- helpers
def target_name() -> str:
    m = platform.machine().lower()
    if sys.platform == "darwin" and m in ("arm64", "aarch64"):
        return "darwin-arm64"
    if sys.platform == "win32" and m in ("amd64", "x86_64"):
        return "win32-x64"
    raise SystemExit(f"unsupported build host {sys.platform}/{m}: targets are darwin-arm64 and win32-x64")


def log(msg: str) -> None:
    print(f"[build_sidecar] {msg}", flush=True)


def fail(msg: str) -> None:
    print(f"[build_sidecar] ERROR: {msg}", file=sys.stderr, flush=True)
    raise SystemExit(1)


def nuitka_info() -> tuple[str, Path]:
    try:
        d = distribution("nuitka")
    except Exception:
        fail('Nuitka is not installed: pip install ".[build]"')
    md = d.metadata
    lic = " ".join([md.get("License-Expression") or "", md.get("License") or "",
                    *[c for c in md.get_all("Classifier") or [] if c.startswith("License ::")]])
    if not re.search(r"Apache", lic) or re.search(r"\bA?GPL|Affero", lic):
        fail(f"Nuitka {d.version} is licensed {lic.strip()!r}; the build requires an Apache-2.0 release (pin nuitka==2.8.10)")
    lic_files = [Path(d.locate_file(f)) for f in d.files or [] if re.search(r"licen[cs]e", str(f), re.I)]
    lic_file = next((p for p in lic_files if p.exists()), None)
    if lic_file is None:
        fail("Nuitka's LICENSE.txt was not found in its distribution")
    return d.version, lic_file


def dir_size(p: Path) -> int:
    return sum(f.stat().st_size for f in p.rglob("*") if f.is_file() and not f.is_symlink())


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# ----------------------------------------------------------------------------- compile
def ensure_macos_sdk() -> None:
    """Make sure clang can link. Some Command Line Tools installs default to a newer SDK than their ld can read
    ("tapi error: malformed file"); then use the newest installed SDK that links, via SDKROOT."""
    if sys.platform != "darwin" or os.environ.get("SDKROOT"):
        return
    with tempfile.TemporaryDirectory(prefix="pdfcore-sdk-") as td:
        src = Path(td) / "t.c"
        src.write_text("int main(void){return 0;}\n")

        def links(env=None) -> bool:
            return subprocess.run(["clang", str(src), "-o", str(Path(td) / "t")], capture_output=True,
                                  env=env).returncode == 0

        if links():
            return
        default = subprocess.run(["xcrun", "--show-sdk-path"], capture_output=True, text=True).stdout.strip()
        sdks = sorted({p.resolve() for p in Path(default).parent.glob("MacOSX*.sdk")},
                      key=lambda p: [int(x) for x in re.findall(r"\d+", p.name)] or [0], reverse=True)
        for sdk in sdks:
            if links(dict(os.environ, SDKROOT=str(sdk))):
                os.environ["SDKROOT"] = str(sdk)
                log(f"default SDK {Path(default).name} does not link with this ld; using SDKROOT={sdk}")
                return
    fail("clang cannot link a test program with any installed macOS SDK")


# Nuitka 2.8.10's POSIX runtime widens the executable's directory to wchar_t one byte at a time through
# mbstowcs(); under a UTF-8 locale any non-ASCII byte makes that fail and the program abort()s before Python
# starts — i.e. the sidecar would crash when installed under a folder like "Ünïcødé" (or "測試") on macOS.
# The build compiles with a patched copy of Nuitka whose appendStringSafeW() decodes UTF-8 (the macOS
# file-system encoding) instead. Nuitka 2.8.x is Apache-2.0, so a modified copy is fine; the change is
# limited to this one function and only applies off Windows (Windows uses the wide-char APIs).
_NUITKA_PATCH_FILE = "build/static_src/HelpersSafeStrings.c"
_NUITKA_PATCH_OLD = """    while (*source != 0) {
        appendCharSafeW(target, *source, buffer_size);
        target++;
        source++;
        buffer_size -= 1;
    }
}"""
_NUITKA_PATCH_NEW = """#if !defined(_WIN32)
    /* pdfcore patch (tools/build_sidecar.py): decode UTF-8 instead of widening byte by byte, so paths with
       non-ASCII characters work under a UTF-8 locale. Invalid bytes map to U+DC80..U+DCFF (surrogateescape),
       as CPython does. */
    unsigned char const *s = (unsigned char const *)source;
    while (*s != 0) {
        unsigned long cp;
        int n;
        if (s[0] < 0x80) {
            cp = s[0], n = 1;
        } else if ((s[0] & 0xE0) == 0xC0 && (s[1] & 0xC0) == 0x80 && s[0] >= 0xC2) {
            cp = ((unsigned long)(s[0] & 0x1F) << 6) | (s[1] & 0x3F), n = 2;
        } else if ((s[0] & 0xF0) == 0xE0 && (s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80) {
            cp = ((unsigned long)(s[0] & 0x0F) << 12) | ((unsigned long)(s[1] & 0x3F) << 6) | (s[2] & 0x3F), n = 3;
        } else if ((s[0] & 0xF8) == 0xF0 && (s[1] & 0xC0) == 0x80 && (s[2] & 0xC0) == 0x80 && (s[3] & 0xC0) == 0x80) {
            cp = ((unsigned long)(s[0] & 0x07) << 18) | ((unsigned long)(s[1] & 0x3F) << 12) |
                 ((unsigned long)(s[2] & 0x3F) << 6) | (s[3] & 0x3F), n = 4;
        } else {
            cp = 0xDC00 + s[0], n = 1;
        }
        appendWCharSafeW(target, (wchar_t)cp, buffer_size);
        target++;
        s += n;
        buffer_size -= 1;
    }
#else
    while (*source != 0) {
        appendCharSafeW(target, *source, buffer_size);
        target++;
        source++;
        buffer_size -= 1;
    }
#endif
}"""


def patched_nuitka(work: Path) -> Path:
    """Copy the installed Nuitka package into the work folder and apply the UTF-8 path patch."""
    import nuitka

    src = Path(nuitka.__file__).resolve().parent
    root = work / "nuitka-patched"
    if root.exists():
        shutil.rmtree(root)
    shutil.copytree(src, root / "nuitka", ignore=shutil.ignore_patterns("__pycache__"))
    f = root / "nuitka" / _NUITKA_PATCH_FILE
    text = f.read_text(encoding="utf-8")
    if _NUITKA_PATCH_OLD not in text or "appendWCharSafeW" not in text:
        fail(f"can't apply the UTF-8 path patch to {_NUITKA_PATCH_FILE} (Nuitka changed?)")
    f.write_text(text.replace(_NUITKA_PATCH_OLD, _NUITKA_PATCH_NEW, 1), encoding="utf-8")
    return root


def compile_nuitka(work: Path, version: str, jobs: int | None) -> Path:
    launcher = work / "pdfcore_sidecar.py"
    launcher.write_text(LAUNCHER, encoding="utf-8")
    skip = sorted(f"pdfcore.{p.stem if p.is_file() else p.name}" for p in (ROOT / "pdfcore").iterdir()
                  if (p.suffix == ".py" or (p.is_dir() and (p / "__init__.py").exists()))
                  and (p.stem if p.is_file() else p.name) not in PDFCORE_KEEP)
    numeric = ".".join((re.findall(r"\d+", version) + ["0", "0", "0"])[:4])
    cmd = [
        sys.executable, "-m", "nuitka", "--mode=standalone", str(launcher),
        f"--output-dir={work}", "--output-filename=pdfcore", "--remove-output",
        "--python-flag=no_site", "--python-flag=isolated", "--python-flag=safe_path",
        "--python-flag=no_docstrings", "--python-flag=no_warnings",
        "--include-module=pdfcore.sidecar", "--include-module=pdfcore.words",
        "--include-package=pypdfium2", "--include-package=pypdfium2_raw", "--include-package=pypdfium2_cfg",
        *[f"--nofollow-import-to={m}" for m in NOFOLLOW + skip],
        "--noinclude-unittest-mode=nofollow", "--noinclude-pytest-mode=nofollow",
        "--noinclude-setuptools-mode=nofollow", "--noinclude-IPython-mode=nofollow",
        "--assume-yes-for-downloads",
        "--product-name=pdfcore", f"--file-version={numeric}", f"--product-version={numeric}",
        "--file-description=pdfcore - PDF words to JSON (PDF Studio)",
        "--copyright=Copyright (c) Owen Smith. MIT License.",
        f"--report={work / 'nuitka-report.xml'}", "--report-diffable",
    ]
    if jobs:
        cmd.append(f"--jobs={jobs}")
    if sys.platform == "win32":
        # Console subsystem so stdout/stderr pipe to the parent; BAR spawns with windowsHide (no flash).
        cmd += ["--windows-console-mode=force", "--msvc=latest"]
    log("nuitka: " + " ".join(cmd[3:6]) + f" … ({len(cmd)} args)")
    env = dict(os.environ, PYTHONPATH=os.pathsep.join([str(patched_nuitka(work)), str(ROOT)]))
    t0 = time.monotonic()
    r = subprocess.run(cmd, cwd=work, env=env)
    if r.returncode:
        fail(f"Nuitka failed (exit {r.returncode})")
    log(f"compiled in {time.monotonic() - t0:.0f} s")
    dist = work / "pdfcore_sidecar.dist"
    if not dist.is_dir():
        fail(f"Nuitka produced no {dist.name}")
    return dist


# ----------------------------------------------------------------------------- licences
def _read(p: Path) -> str:
    return p.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip() + "\n"


def python_license_file() -> Path:
    base = Path(sys.base_prefix)
    for cand in (base / "LICENSE.txt", base / "lib" / f"python{sys.version_info[0]}.{sys.version_info[1]}" / "LICENSE.txt",
                 Path(sysconfig.get_paths()["stdlib"]) / "LICENSE.txt"):
        if cand.exists():
            return cand
    fail(f"CPython's LICENSE.txt was not found under {base}")
    raise AssertionError


def pypdfium2_license_files() -> list[Path]:
    """pypdfium2's own licences plus the PDFium build licences that apply to this build (no V8/XFA, no musl)."""
    d = distribution("pypdfium2")
    try:
        from pypdfium2_raw.version import PDFIUM_INFO
        flags = {f.upper() for f in getattr(PDFIUM_INFO, "flags", ())}
    except Exception:
        flags = set()
    skip_dirs = {"android", "cibw_musl", "pbin_musl"} | (set() if flags & {"V8", "XFA"} else {"v8_xfa"})
    out = []
    for f in d.files or []:
        s = str(f).replace("\\", "/")
        if "/licenses/" not in s:
            continue
        parts = s.split("/licenses/", 1)[1].split("/")
        if len(parts) > 2 and parts[1] in skip_dirs:
            continue
        p = Path(d.locate_file(f))
        if p.is_file():
            out.append((s, p))
    return [p for _, p in sorted(out)]


